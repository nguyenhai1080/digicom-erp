import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from '../node_modules/typescript/lib/typescript.js';
const source=await readFile(new URL('../src/invoice-batch.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {collectIssueGroups,publishIssueGroups}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const item=id=>({id,invoiceNumber:'INV-'+id,payableAmount:'100',currency:'VND',dueDate:'2026-11-01'});
const group=id=>({id,digest:'digest-'+id,items:[item(id)]});
let calls=[];
const grouped=await collectIssueGroups(['a','b','a','c'],async id=>{calls.push(id);return id==='a'?{digest:'ab',items:[item('a'),item('b')]}:group(id);});
assert.deepEqual(calls,['a','c']);assert.equal(grouped.length,2);assert.equal(grouped[0].items.length,2);
assert.equal((await collectIssueGroups([],async()=>{throw Error('Unexpected');})).length,0);
await assert.rejects(collectIssueGroups(['a'],async()=>({digest:'bad',items:[item('b')]})),/chồng lặp/);
await assert.rejects(collectIssueGroups(['a'],async()=>({digest:'bad',items:[item('a'),item('a')]})),/chồng lặp/);
await assert.rejects(collectIssueGroups(['a','c'],async id=>id==='a'?group(id):{digest:'bad',items:[item('a'),item('c')]}),/chồng lặp/);
await assert.rejects(collectIssueGroups(['a','b'],async id=>{if(id==='b')throw Error('Nguồn thay đổi');return group(id);}),/Nguồn thay đổi/);
let published=[],progress=[];
let result=await publishIssueGroups(grouped,async g=>{published.push(g.id);assert.equal(g.digest,g.id==='a'?'ab':'digest-c');return {items:g.items};},n=>progress.push(n));
assert.equal(result.completed,3);assert.equal(result.error,null);assert.deepEqual(published,['a','c']);assert.deepEqual(progress,[2,3]);
published=[];
result=await publishIssueGroups([group('a'),group('b'),group('c')],async g=>{published.push(g.id);if(g.id==='b')throw Error('Mất kết nối, chưa rõ kết quả');return {items:g.items};});
assert.deepEqual(published,['a','b']);assert.equal(result.completed,1);assert.equal(result.failedInvoice,'INV-b');assert.match(result.error,/Mất kết nối/);
published=[];
result=await publishIssueGroups([group('a'),group('b')],async g=>{published.push(g.id);return {items:[item('unexpected')]};});
assert.deepEqual(published,['a']);assert.equal(result.completed,0);assert.match(result.error,/không khớp/);
console.log('Invoice batch checks passed: grouped deduplication, invalid previews, exact digest, success counts, stop after ambiguous failures. No live Invoice was issued.');
